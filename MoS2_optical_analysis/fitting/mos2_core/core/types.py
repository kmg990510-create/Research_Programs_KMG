"""Shared data models for the MoS2 Raman/PL pipeline."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Mapping, MutableMapping, Sequence


@dataclass(slots=True)
class SpectrumRecord:
    """Raw spectrum and metadata from an acquisition source."""

    spectrum_id: str
    x: Sequence[float]
    y: Sequence[float]
    modality: str  # e.g. "raman" or "pl"
    metadata: Mapping[str, Any] = field(default_factory=dict)


@dataclass(slots=True)
class QCSummary:
    """Quality-control result for a single spectrum."""

    passed: bool
    issues: list[str] = field(default_factory=list)
    metrics: Mapping[str, float] = field(default_factory=dict)


@dataclass(slots=True)
class PreprocessedSpectrum:
    """Spectrum after preprocessing (smoothing, normalization, etc.)."""

    spectrum_id: str
    x: Sequence[float]
    y: Sequence[float]
    metadata: Mapping[str, Any] = field(default_factory=dict)


@dataclass(slots=True)
class BaselineCandidate:
    """One candidate baseline generated by a baseline ensemble member."""

    method_name: str
    baseline_y: Sequence[float]
    score: float
    diagnostics: Mapping[str, Any] = field(default_factory=dict)


@dataclass(slots=True)
class BaselineResult:
    """Selected baseline and all baseline candidates for a spectrum."""

    selected: BaselineCandidate
    candidates: list[BaselineCandidate] = field(default_factory=list)


@dataclass(slots=True)
class FitCandidate:
    """One model fit candidate from model ensemble fitting."""

    model_name: str
    params: Mapping[str, float]
    fitted_y: Sequence[float]
    metrics: Mapping[str, float] = field(default_factory=dict)


@dataclass(slots=True)
class FitEnsembleResult:
    """Collection of model candidates for one spectrum."""

    modality: str = "raman"
    candidates: list[FitCandidate] = field(default_factory=list)


@dataclass(slots=True)
class SelectionResult:
    """Best model selected from ensemble candidates."""

    selected: FitCandidate
    rationale: str = ""


@dataclass(slots=True)
class ConfidenceResult:
    """Confidence score that drives review queue generation."""

    score: float
    requires_review: bool
    reasons: list[str] = field(default_factory=list)


@dataclass(slots=True)
class ReviewItem:
    """Record queued for manual review."""

    spectrum_id: str
    reason: str
    confidence_score: float
    metadata: Mapping[str, Any] = field(default_factory=dict)


@dataclass(slots=True)
class ReviewDecision:
    """Manual reviewer decision used to approve/refit/reject."""

    spectrum_id: str
    decision: str  # e.g. "approved", "refit", "rejected"
    reviewer_id: str | None = None
    notes: str = ""
    overrides: Mapping[str, Any] = field(default_factory=dict)


@dataclass(slots=True)
class AcceptedResult:
    """Final accepted fit result after auto/manual review."""

    spectrum_id: str
    fit: FitCandidate
    baseline: BaselineCandidate
    reviewed: bool = False
    review_decision: ReviewDecision | None = None


@dataclass(slots=True)
class ParameterSet:
    """Extracted parameters for a spectrum."""

    spectrum_id: str
    parameters: Mapping[str, float]
    metadata: Mapping[str, Any] = field(default_factory=dict)


@dataclass(slots=True)
class MapAnalysisResult:
    """Map-level analysis output generated from extracted parameters."""

    map_id: str
    layers: Mapping[str, Any] = field(default_factory=dict)
    summary: Mapping[str, Any] = field(default_factory=dict)


@dataclass(slots=True)
class ReportArtifact:
    """Generated report artifact (HTML, PDF, JSON, etc.)."""

    report_id: str
    path: Path
    metadata: Mapping[str, Any] = field(default_factory=dict)


@dataclass(slots=True)
class PipelineResult:
    """Final output container for one pipeline run."""

    qc: Mapping[str, QCSummary]
    flagged: list[ReviewItem]
    decisions: list[ReviewDecision]
    accepted: list[AcceptedResult]
    parameters: list[ParameterSet]
    maps: list[MapAnalysisResult]
    reports: list[ReportArtifact]


@dataclass(slots=True)
class PipelineContext:
    """Shared run context (config, runtime state, and artifact paths)."""

    run_id: str | None = None
    config: Mapping[str, Any] = field(default_factory=dict)
    artifact_dir: Path | None = None
    state: MutableMapping[str, Any] = field(default_factory=dict)
